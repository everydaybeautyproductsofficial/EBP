/**
 * build-review-schema.mjs
 * ─────────────────────────────────────────────────────────────────────────
 * Auto-generates the Organization + AggregateRating + Review JSON-LD schema
 * on reviews.html, using the SAME reviews-data.js the live page renders
 * from — so the schema always exactly matches what a visitor actually sees.
 *
 * IMPORTANT: this ONLY touches reviews.html. It does not add, remove, or
 * duplicate any schema anywhere else on the site (shop.html, category
 * pages, etc. are never opened by this script). There is exactly ONE
 * aggregateRating on the whole site after this runs — this one, built
 * only from your own site's first-party reviews.
 *
 * SAFE TO RE-RUN ANY NUMBER OF TIMES:
 *   - The schema is only ever written between two unique HTML comment
 *     markers in <head>, located by plain string search, so re-running
 *     after adding more reviews just replaces the old block.
 *
 * HOW TO RUN
 * ────────────
 *   node scripts/build-review-schema.mjs
 *
 * Set up scripts/build-review-schema.yml (see setup notes) to have this
 * run automatically on GitHub every time reviews-data.js changes — so you
 * never have to remember to run it by hand after adding a review.
 * ─────────────────────────────────────────────────────────────────────────
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

import { reviews } from '../assets/js/reviews-data.js';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..');
const SITE_URL = 'https://everydaybeautyproducts.com';
const FILE = 'reviews.html';

const MARKER_START = '<!-- REVIEW-SCHEMA:START — auto-generated by scripts/build-review-schema.mjs, do not edit by hand -->';
const MARKER_END   = '<!-- REVIEW-SCHEMA:END -->';

function buildSchema() {
  const total = reviews.length;

  // No reviews yet — write nothing (Google recommends omitting
  // aggregateRating entirely rather than showing 0 reviews / 0 stars).
  if (total === 0) return null;

  const sum = reviews.reduce((acc, r) => acc + r.rating, 0);
  const avg = Math.round((sum / total) * 10) / 10; // 1 decimal place

  return {
    '@context': 'https://schema.org',
    '@type': 'Organization',
    name: 'EverydayBeautyProducts',
    url: `${SITE_URL}/`,
    aggregateRating: {
      '@type': 'AggregateRating',
      ratingValue: String(avg),
      reviewCount: total,
      bestRating: '5',
      worstRating: '1',
    },
    review: reviews.map(r => ({
      '@type': 'Review',
      author: { '@type': 'Person', name: r.name },
      datePublished: r.date,
      reviewRating: {
        '@type': 'Rating',
        ratingValue: r.rating,
        bestRating: '5',
        worstRating: '1',
      },
      reviewBody: r.text,
    })),
  };
}

function injectSchema() {
  const filePath = path.join(ROOT, FILE);
  const original = readFileSync(filePath, 'utf8');

  const schema = buildSchema();
  const block = schema
    ? `${MARKER_START}\n<script type="application/ld+json">${JSON.stringify(schema)}</script>\n${MARKER_END}`
    : `${MARKER_START}\n${MARKER_END}`; // no reviews yet — empty markers, nothing rendered

  const startIdx = original.indexOf(MARKER_START);
  const endIdx = original.indexOf(MARKER_END);

  let html;
  if (startIdx !== -1 && endIdx !== -1 && endIdx > startIdx) {
    // Re-run: replace only the exact span between the existing markers.
    const before = original.slice(0, startIdx);
    const after = original.slice(endIdx + MARKER_END.length);
    html = `${before}${block}${after}`;
  } else if (original.includes('</head>')) {
    // First run: markers don't exist yet — insert just before </head>.
    html = original.replace('</head>', `${block}\n</head>`);
  } else {
    console.warn(`  \u26a0 ${FILE}: no </head> found — schema skipped`);
    return;
  }

  if (html !== original) {
    writeFileSync(filePath, html, 'utf8');
    console.log(`\u2714 ${FILE} — schema written for ${reviews.length} review(s)`);
  } else {
    console.log(`… ${FILE} — no changes`);
  }
}

console.log(`Building review schema from ${reviews.length} review(s) in reviews-data.js\n`);
injectSchema();
console.log('\nDone.');
